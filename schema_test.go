func TestInputSchema(t *testing.T) {
	schema, err := apicontract.InputSchema(notesQuery{})
	if err != nil {
		t.Fatal(err)
	}
	properties := schema["properties"].(map[string]any)
	limit := properties["limit"].(map[string]any)
	if limit["type"] != "integer" || limit["maximum"] != apicontract.MaxLimit || limit["default"] != apicontract.DefaultLimit {
		t.Fatalf("limit = %v", limit)
	}
	if _, ok := properties["updated_from"]; !ok {
		t.Fatalf("prefixed range missing: %v", properties)
	}
	if required := schema["required"].([]string); len(required) != 1 || required[0] != "owner_id" {
		t.Fatalf("required = %v", required)
	}
}

func TestOpenAPIParametersPassLint(t *testing.T) {
	type query struct {
		apicontract.Page
		apicontract.Range
		apicontract.Search
		LegacySearch string `query:"search" deprecated:"q"`
	}
	parameters, err := apicontract.OpenAPIParameters(query{})
	if err != nil {
		t.Fatal(err)
	}
	document := map[string]any{
		"openapi": "3.1.0",
		"info":    map[string]any{"title": "t", "version": "1", apicontract.VersionExtension: apicontract.Version},
		"paths": map[string]any{"/items": map[string]any{"get": map[string]any{
			"parameters": parameters,
			"responses": map[string]any{
				"200": map[string]any{"description": "ok", "content": map[string]any{"application/json": map[string]any{"schema": readSchema(t, "schema/list.json")}}},
				"400": map[string]any{"description": "bad"},
			},
		}}},
	}
	data, _ := json.Marshal(document)
	violations, err := lint.Check("generated", data)
	if err != nil {
		t.Fatal(err)
	}
	if len(violations) > 0 {
		t.Fatalf("parameters generated by the package must meet the contract: %v", violations)
	}
}

func readSchema(t *testing.T, path string) map[string]any {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var schema map[string]any
	if err := json.Unmarshal(data, &schema); err != nil {
		t.Fatal(err)
	}
	return schema
}

func TestOpenAPIParametersOfMatchesReflection(t *testing.T) {
	tagOf := func(v any, i int) reflect.StructTag { return reflect.TypeOf(v).Field(i).Tag }
	fields := []apicontract.Field{
		{Name: "Page", Exported: true, Anonymous: true, Type: apicontract.FieldStruct, Fields: []apicontract.Field{
			{Name: "Limit", Exported: true, Type: apicontract.FieldInt, Tag: tagOf(apicontract.Page{}, 0)},
			{Name: "Cursor", Exported: true, Type: apicontract.FieldString, Tag: tagOf(apicontract.Page{}, 1)},
		}},
		{Name: "Updated", Exported: true, Type: apicontract.FieldStruct, Range: true, Tag: `query:"updated"`, Fields: []apicontract.Field{
			{Name: "From", Exported: true, Type: apicontract.FieldTime, Tag: tagOf(apicontract.Range{}, 0)},
			{Name: "To", Exported: true, Type: apicontract.FieldTime, Tag: tagOf(apicontract.Range{}, 1)},
		}},
		{Name: "Linked", Exported: true, Type: apicontract.FieldBool, Tag: `query:"linked"`},
		{Name: "Owner", Exported: true, Type: apicontract.FieldString, Tag: `query:"owner_id" required:"true"`},
	}
	static, err := apicontract.OpenAPIParametersOf(fields)
	if err != nil {
		t.Fatal(err)
	}
	reflected, err := apicontract.OpenAPIParameters(notesQuery{})
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(static, reflected) {
		t.Fatalf("static %v\nreflected %v", static, reflected)
	}
}
